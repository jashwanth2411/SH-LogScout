"""Read local Windows Security logon events for LogScout-SH.

Only reads Event IDs 4624 (successful logon) and 4625 (failed logon).
No logs are modified, deleted, blocked, or transmitted externally.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
import json
import platform
import subprocess
from typing import Any


class WindowsEventScanError(RuntimeError):
    """Raised when Windows Security events cannot be queried safely."""


def scan_security_events(scan_from: datetime, max_events: int = 1000) -> list[dict[str, Any]]:
    """Read recent local 4624/4625 events and normalize them to LogScout CSV fields."""
    if platform.system() != "Windows":
        raise WindowsEventScanError("Windows auto-scanning is available only when LogScout-SH runs on Windows.")
    if scan_from.tzinfo is None:
        scan_from = scan_from.replace(tzinfo=timezone.utc)
    # Timestamp is generated by Python and restricted to digits/punctuation before embedding.
    start_text = scan_from.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    script = r"""
$ErrorActionPreference = 'Stop'
$startText = '__START_TIME__'
$startTime = [DateTime]::Parse($startText).ToLocalTime()
try {
  $items = @(Get-WinEvent -FilterHashtable @{ LogName='Security'; Id=4624,4625; StartTime=$startTime } -MaxEvents __MAX_EVENTS__ -ErrorAction Stop | ForEach-Object {
    $event = $_
    [xml]$xml = $event.ToXml()
    $fields = @{}
    foreach ($node in $xml.Event.EventData.Data) { $fields[[string]$node.Name] = [string]$node.'#text' }
    $user = $fields['TargetUserName']
    if ([string]::IsNullOrWhiteSpace($user)) { $user = $fields['SubjectUserName'] }
    $ip = $fields['IpAddress']
    if ([string]::IsNullOrWhiteSpace($ip) -or $ip -eq '-') { $ip = 'unknown' }
    [pscustomobject]@{
      record_id = [string]$event.RecordId
      timestamp = $event.TimeCreated.ToUniversalTime().ToString('o')
      username = $(if ([string]::IsNullOrWhiteSpace($user)) { 'unknown' } else { $user })
      source_ip = $ip
      event_type = $(if ($event.Id -eq 4625) { 'login_failed' } else { 'login_success' })
      status = $(if ($event.Id -eq 4625) { 'failed' } else { 'success' })
      event_id = [int]$event.Id
      logon_type = [string]$fields['LogonType']
    }
  })
  if ($items.Count -eq 0) { '[]' } else { ConvertTo-Json -InputObject @($items) -Depth 4 -Compress }
} catch {
  [Console]::Error.WriteLine($_.Exception.Message)
  exit 2
}
"""
    script = script.replace("__START_TIME__", start_text).replace("__MAX_EVENTS__", str(max(1, min(int(max_events), 5000))))
    try:
        result = subprocess.run(
            ["powershell.exe", "-NoLogo", "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "RemoteSigned", "-Command", script],
            capture_output=True, text=True, timeout=25, check=False,
        )
    except FileNotFoundError as exc:
        raise WindowsEventScanError("PowerShell was not found. Run LogScout-SH on a supported Windows system with Windows PowerShell available.") from exc
    except subprocess.TimeoutExpired as exc:
        raise WindowsEventScanError("Windows Security event query timed out. Try a longer scan interval or reduce event volume.") from exc
    if result.returncode != 0:
        message = (result.stderr or result.stdout or "Windows denied access to the Security log.").strip()
        raise WindowsEventScanError(f"Could not read the Windows Security log: {message}")
    output = result.stdout.strip()
    if not output:
        return []
    try:
        payload = json.loads(output)
    except json.JSONDecodeError as exc:
        raise WindowsEventScanError("PowerShell returned an unexpected response while reading the Security log.") from exc
    if isinstance(payload, dict):
        payload = [payload]
    normalized = []
    for row in payload:
        if not isinstance(row, dict):
            continue
        normalized.append({
            "record_id": str(row.get("record_id", "")),
            "timestamp": row.get("timestamp"),
            "username": str(row.get("username") or "unknown"),
            "source_ip": str(row.get("source_ip") or "unknown"),
            "event_type": str(row.get("event_type") or "unknown").lower(),
            "status": str(row.get("status") or "unknown").lower(),
            "event_id": int(row.get("event_id") or 0),
            "logon_type": str(row.get("logon_type") or ""),
        })
    return sorted(normalized, key=lambda item: item.get("timestamp") or "")
